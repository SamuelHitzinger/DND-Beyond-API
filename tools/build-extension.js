import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
// Dependency-free validation of the complete MV3 extension, also used on packages.
const root = new URL('../extensions/dndbeyond/', import.meta.url);
const identity = JSON.parse(await readFile(new URL('../protocol/extension-identity.json', import.meta.url), 'utf8'));
const manifest = JSON.parse(await readFile(new URL('manifest.json', root), 'utf8'));
const derived = createHash('sha256').update(Buffer.from(manifest.key, 'base64')).digest('hex').slice(0, 32).replace(/[0-9a-f]/g, d => String.fromCharCode(97 + parseInt(d, 16)));
if (manifest.key !== identity.manifest_key || derived !== identity.extension_id) throw Error('extension_identity');
if (process.argv.slice(2).some(arg => arg !== '--check')) throw Error('build_arguments');
const generated = '// Generated by tools/build-extension.js from the shared public identity.\n' +
  `export const EXTENSION_ID = ${JSON.stringify(identity.extension_id)};\nexport const NATIVE_HOST = ${JSON.stringify(identity.native_host_name)};\n`;
if (process.argv.includes('--check')) { if (await readFile(new URL('identity.js', root), 'utf8') !== generated) throw Error('extension_identity_stale'); }
else await writeFile(new URL('identity.js', root), generated);
const visited = new Set();
async function visit(url) {
  if (visited.has(url.href)) return; visited.add(url.href);
  if (!url.href.startsWith(root.href)) throw Error('extension_external_dependency');
  const source = await readFile(url, 'utf8'); if (!source.trim()) throw Error('extension_empty_file');
  if (url.pathname.endsWith('.js')) for (const match of source.matchAll(/(?:import|export)\s[^;]*?from\s*['"]([^'"]+)['"]/g)) await visit(new URL(match[1], url));
  if (url.pathname.endsWith('.html')) for (const match of source.matchAll(/(?:src|href)="([^"]+\.(?:js|css|html))"/g)) await visit(new URL(match[1], url));
}
for (const path of [manifest.background.service_worker, manifest.action.default_popup, manifest.options_page]) await visit(new URL(path, root));
if (manifest.content_scripts || manifest.optional_permissions || manifest.permissions.join(',') !== 'nativeMessaging,storage') throw Error('extension_legacy_permissions');
process.stdout.write(`PASS: extension identity and ${visited.size} runtime files verified.\n`);
